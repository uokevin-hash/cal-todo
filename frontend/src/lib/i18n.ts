const DICTS: Record<Lang, Dict> = { ko, en, zh };

export const LOCALES: Record<Lang, string> = { ko: 'ko-KR', en: 'en-US', zh: 'zh-CN' };

export const LANG_OPTIONS: { value: Lang; label: string }[] = [
  { value: 'ko', label: '한국어' },
  { value: 'en', label: 'English' },
  { value: 'zh', label: '中文' },
];

type Params = Record<string, string | number>;

export function translate(lang: Lang, key: Key, params?: Params): string {
  let text = DICTS[lang][key];
  for (const [name, value] of Object.entries(params ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

// 컴포넌트 밖(검증·오류 문구)에서 쓴다. 언어가 바뀌면 화면은 useT로 다시 그려진다
export function t(key: Key, params?: Params): string {
  return translate(useStore.getState().lang, key, params);
}

// 컴포넌트에서 쓴다. 언어가 바뀌면 다시 그린다
export function useT() {
  const lang = useStore((s) => s.lang);
  return (key: Key, params?: Params) => translate(lang, key, params);
}

// 서버에 저장된 이름 중 화면에서 번역해 보이는 값(R-2 기본 그룹, R-9 탈퇴 회원 가림)
export function groupLabel(name: string): string {
  return name === '기본' ? t('defaultGroup') : name;
}
